CREATE INDEX ix_historial_entidad ON historial_estado(entidad, entidad_id, ocurrido_en);

/* Solo se agrega. Unica excepcion: el script de demostracion puede BORRAR
   sus propias filas marcando la transaccion con
   SET LOCAL lis.mantenimiento_demo = '1'; el usuario de la aplicacion
   nunca puede (ademas no tiene permiso de UPDATE/DELETE, 003). */
CREATE FUNCTION historial_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE'
       AND current_setting('lis.mantenimiento_demo', true) = '1'
       AND current_user <> 'lis_app' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'historial_estado es la auditoria del sistema: no se modifica ni se borra.'
        USING ERRCODE = 'insufficient_privilege';
END;
$$;

CREATE TRIGGER tr_historial_inmutable
    BEFORE UPDATE OR DELETE ON historial_estado
    FOR EACH ROW EXECUTE FUNCTION historial_inmutable();

CREATE FUNCTION historial_sin_truncate() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'historial_estado es la auditoria del sistema: no se vacia.'
        USING ERRCODE = 'insufficient_privilege';
END;
$$;

CREATE TRIGGER tr_historial_sin_truncate
    BEFORE TRUNCATE ON historial_estado
    FOR EACH STATEMENT EXECUTE FUNCTION historial_sin_truncate();

/* ---------------------------------------------------------------------
   13. Ciclo de vida: cierres del LIS, tareas, bandeja y correo (D-42)
   --------------------------------------------------------------------- */
CREATE TABLE cierre_lis (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desde      date           NOT NULL,
    hasta      date           NOT NULL,
    motivo     varchar(200)   NOT NULL,
    creado_por integer        NULL REFERENCES usuario(id),
    creado_en  timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_cierre_rango CHECK (desde <= hasta)
);

CREATE TABLE tarea (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo             varchar(20)    NOT NULL,
    clave            varchar(120)   NOT NULL,
    asignacion_id    integer        NULL REFERENCES oferta_x_peticion(id),
    destino_local_id integer        NULL REFERENCES destino_local(id),
    lote_id          integer        NULL REFERENCES lote_fisico(id),
    responsable      varchar(12)    NOT NULL,
    fecha_limite     date           NOT NULL,
    estado           varchar(10)    NOT NULL DEFAULT 'ABIERTA',
    creada_en        timestamptz(0) NOT NULL DEFAULT now(),
    resuelta_por     integer        NULL REFERENCES usuario(id),
    resuelta_en      timestamptz(0) NULL,
