/* =====================================================================
   001 - Esquema LIS Dona en PostgreSQL (Supabase)            D-68
   ---------------------------------------------------------------------
   Equivale al esquema de SQL Server tras sus migraciones 003 a 014
   (db/sqlserver/). Mismas tablas, columnas, restricciones e invariantes.

   Diferencias de motor (misma regla de negocio):
   - Las vistas indexadas de SQL Server (VW_OXP_VIGENTE, VW_LOTE_TITULAR_*)
     se reemplazan por INDICES UNICOS PARCIALES, que Postgres admite con
     IN en el predicado: el motor sigue rechazando dos asignaciones
     vigentes para una peticion o dos titulares para un lote.
   - El trigger del historial inmutable es una funcion plpgsql. La marca
     de sesion del script demo es la variable lis.mantenimiento_demo.
   - Tipos: DATETIME2 -> timestamptz (UTC), NVARCHAR -> varchar,
     BIT -> boolean, TINYINT -> smallint, VARBINARY(MAX) -> bytea.
   - Todo vive en el esquema "lis", que la API REST de Supabase no expone
     (ver 003_seguridad.sql).

   Lo ejecuta backend/scripts/db/migrar.js con el usuario administrador,
   en una sola transaccion.
   ===================================================================== */

CREATE SCHEMA IF NOT EXISTS lis;
SET LOCAL search_path = lis;

/* ---------------------------------------------------------------------
   1. Parametros de configuracion
   --------------------------------------------------------------------- */
CREATE TABLE parametro (
    clave        varchar(60)   NOT NULL PRIMARY KEY,
    valor        varchar(200)  NOT NULL,
    descripcion  varchar(300)  NULL
);

/* ---------------------------------------------------------------------
   2. Identidad, perfiles y roles
   --------------------------------------------------------------------- */
CREATE TABLE usuario (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub         varchar(255)   NOT NULL,
    email              varchar(320)   NOT NULL,
    nombre             varchar(200)   NOT NULL,
    perfil             varchar(20)    NOT NULL,
    activo             boolean        NOT NULL DEFAULT true,
    motivo_bloqueo     varchar(400)   NULL,
    creado_en          timestamptz(0) NOT NULL DEFAULT now(),
    ultimo_ingreso_en  timestamptz(0) NULL,
    CONSTRAINT uq_usuario_google_sub UNIQUE (google_sub),
    CONSTRAINT uq_usuario_email      UNIQUE (email),
    CONSTRAINT ck_usuario_perfil     CHECK (perfil IN ('ESTUDIANTE','DONADOR')),
    CONSTRAINT ck_usuario_bloqueo    CHECK (activo OR motivo_bloqueo IS NOT NULL)
);

CREATE TABLE usuario_rol (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    integer        NOT NULL REFERENCES usuario(id),
    rol           varchar(20)    NOT NULL,
    asignado_por  integer        NULL REFERENCES usuario(id),
    asignado_en   timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuario_rol    UNIQUE (usuario_id, rol),
    CONSTRAINT ck_usuario_rol_rol CHECK (rol IN ('AUXILIAR_LIS','ADMINISTRADOR','SUPERUSUARIO'))
);
CREATE INDEX ix_usuario_rol_usuario ON usuario_rol(usuario_id);

/* ---------------------------------------------------------------------
   3. Catalogos
   --------------------------------------------------------------------- */
CREATE TABLE categoria (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(120)  NOT NULL,
    descripcion   varchar(400)  NULL,
    activa        boolean       NOT NULL DEFAULT true,
    medida_nombre varchar(80)   NULL,
    medida_unidad varchar(60)   NULL,
    medida_min    numeric(9,2)  NULL,
    medida_max    numeric(9,2)  NULL,
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre),
    CONSTRAINT ck_categoria_medida CHECK (
        (medida_nombre IS NULL AND medida_min IS NULL AND medida_max IS NULL)
        OR (medida_nombre IS NOT NULL AND medida_min IS NOT NULL AND medida_max IS NOT NULL AND medida_min < medida_max))
);

CREATE TABLE grupo_sisben (
    codigo             varchar(4)    NOT NULL PRIMARY KEY,
    letra              char(1)       NOT NULL,
    subgrupo           integer       NOT NULL,
    descripcion        varchar(120)  NOT NULL,
    puntaje_necesidad  numeric(6,5)  NOT NULL,
    CONSTRAINT ck_grupo_sisben_letra    CHECK (letra IN ('A','B','C','D')),
    CONSTRAINT ck_grupo_sisben_puntaje  CHECK (puntaje_necesidad >= 0 AND puntaje_necesidad <= 1),
    CONSTRAINT ck_grupo_sisben_subgrupo CHECK (subgrupo > 0)
);

/* ---------------------------------------------------------------------
   4. Caracterizacion del estudiante y certificado de estudio (D-46)
   --------------------------------------------------------------------- */
CREATE TABLE pregunta_caracterizacion (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto  varchar(400)  NOT NULL,
    orden  integer       NOT NULL,
    peso   numeric(6,5)  NOT NULL DEFAULT 1,
    activa boolean       NOT NULL DEFAULT true,
    CONSTRAINT ck_pregunta_peso CHECK (peso > 0)
);

CREATE TABLE opcion_caracterizacion (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id  integer       NOT NULL REFERENCES pregunta_caracterizacion(id),
    texto        varchar(300)  NOT NULL,
    puntaje      numeric(6,5)  NOT NULL,
    orden        integer       NOT NULL,
    CONSTRAINT ck_opcion_puntaje CHECK (puntaje >= 0 AND puntaje <= 1)
);

CREATE TABLE caracterizacion (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      integer        NOT NULL REFERENCES usuario(id),
    grupo_sisben    varchar(4)     NOT NULL REFERENCES grupo_sisben(codigo),
    puntaje_total   numeric(7,5)   NOT NULL,
    completada_en   timestamptz(0) NOT NULL DEFAULT now(),
    actualizada_en  timestamptz(0) NULL,
    CONSTRAINT uq_caract_usuario UNIQUE (usuario_id),
    CONSTRAINT ck_caract_puntaje CHECK (puntaje_total >= 0 AND puntaje_total <= 1)
);

CREATE TABLE respuesta_caracterizacion (
    caracterizacion_id integer NOT NULL REFERENCES caracterizacion(id) ON DELETE CASCADE,
    pregunta_id        integer NOT NULL REFERENCES pregunta_caracterizacion(id),
    opcion_id          integer NOT NULL REFERENCES opcion_caracterizacion(id),
    CONSTRAINT pk_respuesta PRIMARY KEY (caracterizacion_id, pregunta_id)
);

CREATE TABLE certificado_estudio (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       integer        NOT NULL REFERENCES usuario(id),
    contenido        bytea          NOT NULL,
    mime             varchar(100)   NOT NULL,
    tamano_bytes     integer        NOT NULL,
    hash_sha256      char(64)       NOT NULL,
    nombre_original  varchar(260)   NULL,
    subido_en        timestamptz(0) NOT NULL DEFAULT now(),
    estado_revision  varchar(12)    NOT NULL DEFAULT 'PENDIENTE',
    revisado_por     integer        NULL REFERENCES usuario(id),
    revisado_en      timestamptz(0) NULL,
    observacion      varchar(400)   NULL,
    CONSTRAINT uq_cert_usuario  UNIQUE (usuario_id),
    CONSTRAINT ck_cert_mime     CHECK (mime IN ('application/pdf','image/jpeg','image/png')),
    CONSTRAINT ck_cert_estado   CHECK (estado_revision IN ('PENDIENTE','VALIDADO','RECHAZADO')),
    CONSTRAINT ck_cert_revision CHECK (
        (estado_revision = 'PENDIENTE' AND revisado_por IS NULL AND revisado_en IS NULL) OR
        (estado_revision <> 'PENDIENTE' AND revisado_por IS NOT NULL AND revisado_en IS NOT NULL))
);

/* ---------------------------------------------------------------------
   5. Evidencia fotografica (D-36): dentro de la BD, nunca URL publica
   --------------------------------------------------------------------- */
CREATE TABLE evidencia (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenido       bytea          NOT NULL,
    mime            varchar(100)   NOT NULL,
    tamano_bytes    integer        NOT NULL,
    hash_sha256     char(64)       NOT NULL,
    nombre_original varchar(260)   NULL,
    subida_por      integer        NOT NULL REFERENCES usuario(id),
    subida_en       timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_evidencia_tamano CHECK (tamano_bytes > 0),
    CONSTRAINT ck_evidencia_mime   CHECK (mime IN ('image/jpeg','image/png','image/webp'))
);

/* ---------------------------------------------------------------------
   6. Oferta (la publica el donador; la aprueba el LIS)
   --------------------------------------------------------------------- */
CREATE TABLE oferta (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donador_id          integer        NOT NULL REFERENCES usuario(id),
    categoria_id        integer        NOT NULL REFERENCES categoria(id),
    nombre_producto     varchar(200)   NOT NULL,
    descripcion         varchar(1000)  NOT NULL,
    cantidad            integer        NOT NULL,
    estado              varchar(25)    NOT NULL,
    foto_id             integer        NULL REFERENCES evidencia(id),
    creada_en           timestamptz(0) NOT NULL DEFAULT now(),
    actualizada_en      timestamptz(0) NULL,
    revisada_por        integer        NULL REFERENCES usuario(id),
    revisada_en         timestamptz(0) NULL,
    motivo_rechazo      varchar(400)   NULL,
    cerrada_en          timestamptz(0) NULL,
    estado_conservacion smallint       NOT NULL DEFAULT 3,
    medida              numeric(9,2)   NULL,
    origen              varchar(10)    NOT NULL DEFAULT 'DONADOR',
    oferta_origen_id    integer        NULL REFERENCES oferta(id),
    CONSTRAINT ck_oferta_cantidad     CHECK (cantidad > 0),
    CONSTRAINT ck_oferta_estado       CHECK (estado IN ('PENDIENTE_APROBACION','APROBADA','RECHAZADA','CANCELADA','CERRADA')),
    CONSTRAINT ck_oferta_revision     CHECK (estado <> 'APROBADA' OR (revisada_por IS NOT NULL AND revisada_en IS NOT NULL)),
    CONSTRAINT ck_oferta_rechazo      CHECK (estado <> 'RECHAZADA' OR (revisada_por IS NOT NULL AND revisada_en IS NOT NULL AND motivo_rechazo IS NOT NULL)),
    CONSTRAINT ck_oferta_conservacion CHECK (estado_conservacion BETWEEN 1 AND 5),
    CONSTRAINT ck_oferta_origen       CHECK ((origen = 'DONADOR' AND oferta_origen_id IS NULL) OR (origen = 'FALTANTE' AND oferta_origen_id IS NOT NULL))
);
CREATE INDEX ix_oferta_estado_categoria ON oferta(estado, categoria_id);
CREATE INDEX ix_oferta_donador          ON oferta(donador_id, estado);

/* ---------------------------------------------------------------------
   7. Peticion (sin cantidad solicitada, D-10)
   --------------------------------------------------------------------- */
CREATE TABLE peticion (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id  integer        NOT NULL REFERENCES usuario(id),
    categoria_id   integer        NOT NULL REFERENCES categoria(id),
    descripcion    varchar(1000)  NOT NULL,
    estado         varchar(25)    NOT NULL,
    creada_en      timestamptz(0) NOT NULL DEFAULT now(),
    actualizada_en timestamptz(0) NULL,
    revisada_por   integer        NULL REFERENCES usuario(id),
    revisada_en    timestamptz(0) NULL,
    motivo_rechazo varchar(400)   NULL,
    cerrada_en     timestamptz(0) NULL,
    motivo_cierre  varchar(400)   NULL,
    estado_minimo  smallint       NOT NULL DEFAULT 1,
    medida_min     numeric(9,2)   NULL,
    medida_max     numeric(9,2)   NULL,
    CONSTRAINT ck_peticion_estado        CHECK (estado IN ('PENDIENTE_APROBACION','APROBADA','RECHAZADA','CANCELADA','CERRADA_ENTREGA','CERRADA_INCUMPLIMIENTO')),
    CONSTRAINT ck_peticion_revision      CHECK (estado <> 'APROBADA' OR (revisada_por IS NOT NULL AND revisada_en IS NOT NULL)),
    CONSTRAINT ck_peticion_rechazo       CHECK (estado <> 'RECHAZADA' OR (revisada_por IS NOT NULL AND revisada_en IS NOT NULL AND motivo_rechazo IS NOT NULL)),
    CONSTRAINT ck_peticion_estado_minimo CHECK (estado_minimo BETWEEN 1 AND 5),
    CONSTRAINT ck_peticion_medida        CHECK (medida_min IS NULL OR medida_max IS NULL OR medida_min <= medida_max)
);
CREATE INDEX ix_peticion_estado_categoria ON peticion(estado, categoria_id, creada_en);
CREATE INDEX ix_peticion_estudiante       ON peticion(estudiante_id, estado);

/* ---------------------------------------------------------------------
   8. Oferta_x_peticion (intento de asignacion)
   --------------------------------------------------------------------- */
CREATE TABLE oferta_x_peticion (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id               integer        NOT NULL REFERENCES oferta(id),
    peticion_id             integer        NOT NULL REFERENCES peticion(id),
    cantidad_asignada       integer        NOT NULL,
    estado                  varchar(20)    NOT NULL,
    puntaje_prioridad       numeric(8,6)   NULL,
    asignada_por            integer        NOT NULL REFERENCES usuario(id),
    asignada_en             timestamptz(0) NOT NULL DEFAULT now(),
    recibida_en             timestamptz(0) NULL,
    entregada_en            timestamptz(0) NULL,
    cerrada_en              timestamptz(0) NULL,
    motivo_cierre           varchar(400)   NULL,
    puntaje_sisben          numeric(8,6)   NULL,
    puntaje_caracterizacion numeric(8,6)   NULL,
    puntaje_antiguedad      numeric(8,6)   NULL,
    coeficientes_prioridad  varchar(120)   NULL,
    lote_id                 integer        NULL,   -- FK al final (ciclo con lote_fisico)
    origen                  varchar(15)    NOT NULL DEFAULT 'DONADOR',
    custodia_desde          timestamptz(0) NULL,
    dias_extra              integer        NOT NULL DEFAULT 0,
    aplazamientos           integer        NOT NULL DEFAULT 0,
    CONSTRAINT ck_oxp_cantidad CHECK (cantidad_asignada > 0),
    CONSTRAINT ck_oxp_estado   CHECK (estado IN ('ASIGNADO','EN_CUSTODIA','ENTREGADO','DEVOLUCION','CANCELADO')),
    CONSTRAINT ck_oxp_custodia CHECK (estado NOT IN ('EN_CUSTODIA','ENTREGADO','DEVOLUCION') OR recibida_en IS NOT NULL),
    CONSTRAINT ck_oxp_entrega  CHECK (estado <> 'ENTREGADO' OR entregada_en IS NOT NULL),
    CONSTRAINT ck_oxp_cierre   CHECK (estado NOT IN ('CANCELADO','DEVOLUCION') OR motivo_cierre IS NOT NULL),
    CONSTRAINT ck_oxp_origen   CHECK (origen = 'DONADOR' OR (origen = 'REASIGNACION' AND lote_id IS NOT NULL)),
    CONSTRAINT ck_oxp_prorroga CHECK (dias_extra >= 0 AND aplazamientos >= 0)
);
CREATE INDEX ix_oxp_oferta   ON oferta_x_peticion(oferta_id, estado);
CREATE INDEX ix_oxp_peticion ON oferta_x_peticion(peticion_id, asignada_en);
/* "Una sola asignacion vigente por peticion" (antes VW_OXP_VIGENTE). */
CREATE UNIQUE INDEX ux_oxp_vigente_por_peticion
    ON oferta_x_peticion(peticion_id) WHERE estado IN ('ASIGNADO','EN_CUSTODIA');

/* ---------------------------------------------------------------------
   9. Movimiento fisico (inmutable). Foto obligatoria. Pertenece a un
      intento O a un destino Local (arco exclusivo).
   --------------------------------------------------------------------- */
CREATE TABLE movimiento (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_x_peticion_id  integer        NULL REFERENCES oferta_x_peticion(id),
    tipo                  varchar(15)    NOT NULL,
    cantidad              integer        NOT NULL,
    nombre_contraparte    varchar(200)   NOT NULL,
    evidencia_id          integer        NOT NULL REFERENCES evidencia(id),
    observaciones         varchar(600)   NULL,
    registrado_por        integer        NOT NULL REFERENCES usuario(id),
    registrado_en         timestamptz(0) NOT NULL DEFAULT now(),
    destino_local_id      integer        NULL,   -- FK al final
    lote_id               integer        NULL,   -- FK al final
    CONSTRAINT ck_movimiento_tipo     CHECK (tipo IN ('RECEPCION','ENTREGA','DEVOLUCION')),
    CONSTRAINT ck_movimiento_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_movimiento_titular  CHECK (
        (oferta_x_peticion_id IS NOT NULL AND destino_local_id IS NULL)
        OR (oferta_x_peticion_id IS NULL AND destino_local_id IS NOT NULL))
);
CREATE INDEX ix_movimiento_oxp   ON movimiento(oferta_x_peticion_id, registrado_en);
CREATE INDEX ix_movimiento_local ON movimiento(destino_local_id) WHERE destino_local_id IS NOT NULL;

/* ---------------------------------------------------------------------
   10. Lote fisico: unidades que el LIS tiene o tuvo en sus manos
   --------------------------------------------------------------------- */
CREATE TABLE lote_fisico (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id               integer        NOT NULL REFERENCES oferta(id),
    cantidad                integer        NOT NULL,
    ubicacion               varchar(20)    NOT NULL,
    origen                  varchar(25)    NOT NULL,
    intento_origen_id       integer        NULL REFERENCES oferta_x_peticion(id),
    recepcion_movimiento_id integer        NULL REFERENCES movimiento(id),
    sin_destino_desde       timestamptz(0) NULL,
    creado_en               timestamptz(0) NOT NULL DEFAULT now(),
    actualizado_en          timestamptz(0) NULL,
    CONSTRAINT ck_lote_cantidad  CHECK (cantidad > 0),
    CONSTRAINT ck_lote_ubicacion CHECK (ubicacion IN ('EN_LIS','ENTREGADO','DEVUELTO','PATRIMONIO_LIS')),
    CONSTRAINT ck_lote_origen    CHECK (origen IN ('RECEPCION_ASIGNACION','RECEPCION_INCOMPLETA','RECEPCION_LOCAL'))
);
CREATE UNIQUE INDEX uq_lote_recepcion ON lote_fisico(recepcion_movimiento_id) WHERE recepcion_movimiento_id IS NOT NULL;
CREATE INDEX ix_lote_oferta ON lote_fisico(oferta_id, ubicacion);

/* ---------------------------------------------------------------------
   11. Destino Local: el LIS como destinatario institucional (D-43, D-50)
   --------------------------------------------------------------------- */
CREATE TABLE destino_local (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id                 integer        NOT NULL REFERENCES oferta(id),
    lote_id                   integer        NULL REFERENCES lote_fisico(id),
    origen                    varchar(10)    NOT NULL,
    cantidad                  integer        NOT NULL,
    estado                    varchar(20)    NOT NULL,
    seleccionado_por          integer        NOT NULL REFERENCES usuario(id),
    seleccionado_en           timestamptz(0) NOT NULL DEFAULT now(),
    motivo                    varchar(400)   NOT NULL,
    custodia_desde            timestamptz(0) NULL,
    aceptacion_solicitada_por integer        NULL REFERENCES usuario(id),
    aceptacion_solicitada_en  timestamptz(0) NULL,
    aceptado_por              integer        NULL REFERENCES usuario(id),
    aceptado_en               timestamptz(0) NULL,
    cerrado_en                timestamptz(0) NULL,
    motivo_cierre             varchar(400)   NULL,
    propuesta_motivo          varchar(400)   NULL,
    propuesta_limite          date           NULL,
    respuesta_donador         varchar(10)    NULL,
    respuesta_en              timestamptz(0) NULL,
    respuesta_motivo          varchar(400)   NULL,
    CONSTRAINT ck_local_cantidad  CHECK (cantidad > 0),
    CONSTRAINT ck_local_origen    CHECK (origen IN ('OFERTA','LOTE')),
    CONSTRAINT ck_local_estado    CHECK (estado IN ('ESPERA_RECEPCION','CUSTODIA_TEMPORAL','PROPUESTO_DONADOR','POR_DEVOLVER',
                                                    'ACEPTADO','REASIGNADO','DEVUELTO','CANCELADO')),
    CONSTRAINT ck_local_lote      CHECK (origen = 'OFERTA' OR lote_id IS NOT NULL),
    CONSTRAINT ck_local_fisico    CHECK (estado IN ('ESPERA_RECEPCION','CANCELADO') OR lote_id IS NOT NULL),
    CONSTRAINT ck_local_aceptado  CHECK (estado <> 'ACEPTADO' OR (aceptado_por IS NOT NULL AND aceptado_en IS NOT NULL)),
    CONSTRAINT ck_local_cierre    CHECK (estado NOT IN ('REASIGNADO','DEVUELTO','CANCELADO') OR motivo_cierre IS NOT NULL),
    CONSTRAINT ck_local_respuesta CHECK (respuesta_donador IS NULL OR respuesta_donador IN ('ACEPTA','RECHAZA')),
    CONSTRAINT ck_local_propuesta CHECK (estado <> 'PROPUESTO_DONADOR' OR (
        aceptacion_solicitada_por IS NOT NULL AND aceptacion_solicitada_en IS NOT NULL
        AND propuesta_motivo IS NOT NULL AND propuesta_limite IS NOT NULL))
);

/* Referencias del ciclo intento <-> lote <-> movimiento <-> Local. */
ALTER TABLE oferta_x_peticion ADD CONSTRAINT fk_oxp_lote          FOREIGN KEY (lote_id)          REFERENCES lote_fisico(id);
