    ON destino_local(lote_id) WHERE lote_id IS NOT NULL AND estado IN ('CUSTODIA_TEMPORAL','PROPUESTO_DONADOR','POR_DEVOLVER');

/* ---------------------------------------------------------------------
   12. Historial de estados (auditoria inmutable, D-65 S3)
   --------------------------------------------------------------------- */
CREATE TABLE historial_estado (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad         varchar(20)    NOT NULL,
    entidad_id      integer        NOT NULL,
    estado_anterior varchar(25)    NULL,
    estado_nuevo    varchar(25)    NOT NULL,
    actor_id        integer        NULL REFERENCES usuario(id),
