ALTER TABLE movimiento        ADD CONSTRAINT fk_movimiento_lote   FOREIGN KEY (lote_id)          REFERENCES lote_fisico(id);

/* "Un solo titular vigente por lote" (antes VW_LOTE_TITULAR_OXP y _LOCAL). */
CREATE UNIQUE INDEX ux_lote_titular_oxp
    ON oferta_x_peticion(lote_id) WHERE lote_id IS NOT NULL AND estado IN ('EN_CUSTODIA','DEVOLUCION');
