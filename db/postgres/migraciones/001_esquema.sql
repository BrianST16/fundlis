/* ---------------------------------------------------------------------
   14. Saldo de oferta (debe coincidir con backend/src/ofertas/saldo.ts)
       Consumen unidades de la oferta:
        A) intentos de origen DONADOR vigentes o cerrados, y los CANCELADOS
           despues de una recepcion (las unidades ya estan en un lote);
        B) destinos Local elegidos desde la oferta y no cancelados;
        C) lotes de una oferta generada por faltante.
       security_invoker: se evalua con los permisos de quien consulta.
   --------------------------------------------------------------------- */
CREATE VIEW vw_oferta_saldo WITH (security_invoker = true) AS
SELECT o.id AS oferta_id,
       o.cantidad AS cantidad_ofertada,
       COALESCE(a.comprometida, 0) AS cantidad_comprometida,
       COALESCE(a.consumida, 0)    AS cantidad_consumida_intentos,
       COALESCE(b.local_cant, 0)   AS cantidad_destino_local,
       COALESCE(c.faltante, 0)     AS cantidad_en_lote_faltante,
       o.cantidad - COALESCE(a.comprometida, 0) - COALESCE(a.consumida, 0)
                  - COALESCE(b.local_cant, 0) - COALESCE(c.faltante, 0) AS cantidad_disponible
FROM oferta o
LEFT JOIN LATERAL (
    SELECT SUM(CASE WHEN x.estado = 'ASIGNADO' THEN x.cantidad_asignada END) AS comprometida,
           SUM(CASE WHEN x.estado IN ('EN_CUSTODIA','ENTREGADO','DEVOLUCION')
                      OR (x.estado = 'CANCELADO' AND x.recibida_en IS NOT NULL) THEN x.cantidad_asignada END) AS consumida
    FROM oferta_x_peticion x WHERE x.oferta_id = o.id AND x.origen = 'DONADOR') a ON true
LEFT JOIN LATERAL (
    SELECT SUM(d.cantidad) AS local_cant FROM destino_local d
    WHERE d.oferta_id = o.id AND d.origen = 'OFERTA' AND d.estado <> 'CANCELADO') b ON true
LEFT JOIN LATERAL (
    SELECT SUM(l.cantidad) AS faltante FROM lote_fisico l
    WHERE l.oferta_id = o.id AND o.origen = 'FALTANTE') c ON true;
